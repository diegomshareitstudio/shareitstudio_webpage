// @ts-check
/**
 * Server rules for HostArmada (Apache/LiteSpeed shared hosting), written next to the static files on every build.
 * The deploy uploads the contents of dist/ to public_html/v2/, so these files REPLACE whatever is on the server:
 *
 * - dist/.htaccess          301s for old URLs, password protection (staging), noindex (staging), compression,
 *                           caching of pages, security headers
 * - dist/_astro/.htaccess   one-year caching for hashed assets (their names change whenever their content does)
 *
 * Password protection: cPanel "Directory Privacy" stores its rules in public_html/v2/.htaccess, which a deploy would
 * overwrite. So the build writes those rules itself, from HTACCESS_AUTH_USERFILE (the AuthUserFile path cPanel
 * created, e.g. /home/<user>/.htpasswds/public_html/v2/passwd). In CI (GitHub Actions) the build refuses to run
 * without it, so a deploy can never publish the site unprotected by accident. Set it to "none" to turn it off
 * (e.g. when the site goes public).
 */
import { writeFile } from 'node:fs/promises';

/**
 * @param {object} options
 * @param {string} options.base The site's base path, e.g. "/v2/"
 * @param {Record<string, string>} options.redirects Old path → new path, both without the base
 * @param {string | undefined} options.authUserFile Value of HTACCESS_AUTH_USERFILE
 * @returns {import('astro').AstroIntegration}
 */
export default function hostArmada({ base, redirects, authUserFile }) {
  const root = base.replace(/\/$/, ''); // "/v2" ("" at the domain root)
  const staging = root !== '';
  const auth = authUserFile && authUserFile !== 'none' ? authUserFile : null;

  const redirectRules = Object.entries(redirects)
    .map(([from, to]) => `RedirectMatch 301 ^${root}${from}/?$ ${root}${to}/`)
    .join('\n');

  const authRules = auth
    ? `# Password protection (same rules cPanel "Directory Privacy" writes; kept here so a deploy never removes them)
AuthType Basic
AuthName "Share It Studio"
AuthUserFile "${auth}"
Require valid-user
`
    : '';

  const htaccess = `# Generated on every build by integrations/hostarmada.mjs. Change it there and redeploy; do not edit on the server.
Options -Indexes
DirectoryIndex index.html index.php

${authRules}
# Old URLs (301)
${redirectRules}

# MIME types some hosts lack
AddType font/woff2 .woff2
AddType image/webp .webp
AddType video/mp4 .mp4

# Compression (LiteSpeed also compresses on its own)
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
${staging ? '  # Staging copy under a sub-path: never indexed, even if the password protection is removed\n  Header always set X-Robots-Tag "noindex, nofollow"\n' : ''}  # Pages are checked on every visit, so a new deploy shows up at once
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  # Unhashed media (favicon, videos): one week
  <FilesMatch "\\.(ico|svg|mp4|webm|vtt)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>
`;

  const assets = `# Generated by integrations/hostarmada.mjs. Hashed file names: safe to cache for a year.
<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`;

  return {
    name: 'hostarmada',
    hooks: {
      'astro:config:setup': ({ command, logger }) => {
        if (command !== 'build' || auth || authUserFile === 'none') return;
        if (process.env.CI) {
          throw new Error(
            'HTACCESS_AUTH_USERFILE is not set. Without it the deploy would replace the server .htaccess and remove ' +
              'the password protection of the site. Set it to the AuthUserFile path from cPanel, or to "none".',
          );
        }
        logger.warn('HTACCESS_AUTH_USERFILE is not set: dist/.htaccess has no password protection.');
      },
      'astro:build:done': async ({ dir }) => {
        await writeFile(new URL('.htaccess', dir), htaccess);
        await writeFile(new URL('_astro/.htaccess', dir), assets);
      },
    },
  };
}
